import json
import re

with open('scraped_data/all_articles.json', 'r', encoding='utf-8') as f:
    raw_articles = json.load(f)

clean_articles = []
for a in raw_articles:
    title = a['title'].replace(' | Tel2tell', '').strip()
    
    # Categorize
    t = title.lower()
    if any(k in t for k in ['vdo', 'video', 'วิดีโอ', 'วีดีโอ', 'production', 'อีเวนต์', 'อีเว้นท์']):
        category = 'VDO & Production'
    elif any(k in t for k in ['telesales', 'tele-sales', 'tele sale', 'sales admin', 'ขายทางโทรศัพท์', 'ยอดขาย', 'outbound']):
        category = 'Telesales & Outbound'
    elif any(k in t for k in ['รางวัล', 'award', 'tccta', '1668', 'บริจาค', 'ช่วยเหลือ', 'ทำบุญ', 'บวงสรวง', 'กิจกรรม', 'party']):
        category = 'CSR & Company'
    elif any(k in t for k in ['fulfilment', 'fulfillment', 'logistics', 'คลังสินค้า']):
        category = 'Logistics & Partner'
    else:
        category = 'Call Center Knowledge'
        
    # Get clean excerpt
    body = a['body_text']
    # remove repetitive nav text if present
    lines = [l.strip() for l in body.split('\n') if l.strip() and len(l.strip()) > 10 and not any(ign in l for ign in ['Arapapa Shop', 'FG Logistic', 'Tel2Solar', 'Forum', '0890404627', 'EMAIL nattapon@', 'Copyright 2017', 'ผู้เข้าชม'])]
    
    clean_body = "\n\n".join(lines[:30])
    excerpt = lines[0] if lines else a['meta_description']
    if len(excerpt) > 160:
        excerpt = excerpt[:157] + '...'
        
    imgs = [img['src'] for img in a['images'] if not img['src'].startswith('data:')]
    
    clean_articles.append({
        'id': a['id'],
        'title': title,
        'category': category,
        'excerpt': excerpt,
        'content': clean_body,
        'image': imgs[0] if imgs else 'images/articles/art_1.png',
        'url': a['url']
    })

print(f"Processed {len(clean_articles)} articles.")

with open('articles-data.js', 'w', encoding='utf-8') as f:
    f.write("// Autogenerated Tel2Tell Articles Data\n")
    f.write("window.TEL2TELL_ARTICLES = ")
    json.dump(clean_articles, f, ensure_ascii=False, indent=2)
    f.write(";\n")

print("articles-data.js created successfully!")
